import Link from "next/link";
import StatusBadge from "@/components/StatusBadge";
import { cardClass } from "@/components/styles";
import { formatDate, requireAdmin } from "@/lib/admin";
import { formatMs } from "@/lib/observability";

export const dynamic = "force-dynamic";

type Run = {
  id: string;
  source: string;
  status: string;
  error: string | null;
  image_url: string | null;
  duration_ms: number | null;
  created_at: string;
  photos: { image_url: string; neighborhood: string | null } | null;
  llm_responses: { step_order: number; ok: boolean; response_text: string | null; model: string }[];
};

function captionsFrom(run: Run) {
  const final = run.llm_responses.filter((r) => r.ok).sort((a, b) => b.step_order - a.step_order)[0];
  try {
    const parsed = JSON.parse(final?.response_text ?? "");
    return Array.isArray(parsed) ? parsed.filter((c): c is string => typeof c === "string") : [];
  } catch {
    return [];
  }
}

export default async function MediaPage({ params }: PageProps<"/chains/[id]/media">) {
  const { id } = await params;
  const { supabase } = await requireAdmin();
  const { data, error } = await supabase
    .from("generation_requests")
    .select("id, source, status, error, image_url, duration_ms, created_at, photos (image_url, neighborhood), llm_responses (step_order, ok, response_text, model)")
    .eq("chain_id", id)
    .order("created_at", { ascending: false })
    .limit(60);
  const runs = (data ?? []) as unknown as Run[];

  return (
    <div className="space-y-4">
      {error && <p className="font-mono text-sm text-rouge">Couldn&apos;t load media: {error.message}. Has chain-tool.sql been run?</p>}
      {runs.length === 0 && !error && (
        <p className="font-mono text-sm text-muted">
          Nothing generated by this chain yet. <Link href={`/chains/${id}/generate`} className="underline underline-offset-4">Run it</Link> to see results here.
        </p>
      )}
      <ul className="grid gap-4 md:grid-cols-2">
        {runs.map((run) => {
          const image = run.photos?.image_url ?? run.image_url;
          const captions = captionsFrom(run);
          return (
            <li key={run.id} className={`${cardClass} overflow-hidden`}>
              {image && (
                // eslint-disable-next-line @next/next/no-img-element
                <img src={image} alt="" className="aspect-[4/3] w-full object-cover" />
              )}
              <div className="space-y-2 p-4">
                <div className="flex flex-wrap items-center gap-2 font-mono text-xs text-muted">
                  <StatusBadge status={run.status} />
                  <span>{formatDate(run.created_at)}</span>
                  <span>· {run.source === "tool" ? "test run" : "from the app"}</span>
                  <span>· {formatMs(run.duration_ms)}</span>
                </div>
                {captions.length > 0 && (
                  <ol className="list-decimal space-y-1 pl-5 font-mono text-sm">
                    {captions.map((caption) => (
                      <li key={caption}>{caption}</li>
                    ))}
                  </ol>
                )}
                {run.error && <p className="font-mono text-xs text-rouge">{run.error}</p>}
              </div>
            </li>
          );
        })}
      </ul>
    </div>
  );
}
